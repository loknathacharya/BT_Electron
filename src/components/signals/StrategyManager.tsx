import React, { useState, useEffect } from 'react';
import { SignalStrategy } from '../../types/signals';
import { ExpressionBuilder } from './ExpressionBuilder';

interface StrategyManagerProps {
  onSelectStrategy?: (strategyId: string) => void;
}

export const StrategyManager: React.FC<StrategyManagerProps> = ({ onSelectStrategy }) => {
  const [strategies, setStrategies] = useState<SignalStrategy[]>([]);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [showCreateModal, setShowCreateModal] = useState(false);
  const [editingStrategy, setEditingStrategy] = useState<SignalStrategy | null>(null);

  useEffect(() => {
    loadStrategies();
  }, []);

  const loadStrategies = async () => {
    setLoading(true);
    setError(null);

    try {
      const result = await window.electron.invoke('get_signal_strategies', {});
      if (result.success && result.strategies) {
        setStrategies(result.strategies);
      } else {
        setError(result.error || 'Failed to load strategies');
      }
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to load strategies');
    } finally {
      setLoading(false);
    }
  };

  const handleDelete = async (strategyId: string) => {
    if (!confirm('Are you sure you want to delete this strategy? This cannot be undone.')) return;

    try {
      const result = await window.electron.invoke('delete_signal_strategy', strategyId);
      if (result.success) {
        loadStrategies();
      } else {
        alert(`Failed to delete strategy: ${result.error}`);
      }
    } catch (err) {
      alert(`Error: ${err instanceof Error ? err.message : 'Unknown error'}`);
    }
  };

  const handleDuplicate = async (strategy: SignalStrategy) => {
    const newStrategy: SignalStrategy = {
      ...strategy,
      id: '', // Will be generated by backend
      name: `${strategy.name} (Copy)`,
      created_at: Date.now() / 1000,
      updated_at: Date.now() / 1000,
      version: 1
    };
    setEditingStrategy(newStrategy);
    setShowCreateModal(true);
  };

  const handleEdit = (strategy: SignalStrategy) => {
    setEditingStrategy(strategy);
    setShowCreateModal(true);
  };

  return (
    <div className="strategy-manager">
      <div className="manager-header">
        <h1>Strategy Manager</h1>
        <button
          onClick={() => {
            setEditingStrategy(null);
            setShowCreateModal(true);
          }}
          className="button-primary"
        >
          + Create Strategy
        </button>
      </div>

      {error && (
        <div className="error-banner">
          {error}
        </div>
      )}

      <div className="strategies-grid">
        {loading ? (
          <div className="loading">Loading strategies...</div>
        ) : strategies.length === 0 ? (
          <div className="no-strategies">
            <p>No strategies found. Create your first strategy to get started!</p>
            <button onClick={() => setShowCreateModal(true)} className="button-primary">
              Create Strategy
            </button>
          </div>
        ) : (
          strategies.map(strategy => (
            <StrategyCard
              key={strategy.id}
              strategy={strategy}
              onEdit={() => handleEdit(strategy)}
              onDuplicate={() => handleDuplicate(strategy)}
              onDelete={() => handleDelete(strategy.id)}
              onSelect={() => onSelectStrategy?.(strategy.id)}
            />
          ))
        )}
      </div>

      {showCreateModal && (
        <StrategyFormModal
          strategy={editingStrategy}
          onClose={() => {
            setShowCreateModal(false);
            setEditingStrategy(null);
          }}
          onSuccess={() => {
            setShowCreateModal(false);
            setEditingStrategy(null);
            loadStrategies();
          }}
        />
      )}

      <style>{`
        .strategy-manager {
          padding: 2rem;
          max-width: 1200px;
          margin: 0 auto;
        }

        .manager-header {
          display: flex;
          justify-content: space-between;
          align-items: center;
          margin-bottom: 2rem;
        }

        .manager-header h1 {
          margin: 0;
          font-size: 2rem;
        }

        .error-banner {
          background: #ffebee;
          border: 1px solid #ef5350;
          padding: 1rem;
          border-radius: 4px;
          margin-bottom: 1rem;
          color: #c62828;
        }

        .strategies-grid {
          display: grid;
          grid-template-columns: repeat(auto-fill, minmax(350px, 1fr));
          gap: 1.5rem;
        }

        .loading,
        .no-strategies {
          text-align: center;
          padding: 3rem;
          color: #999;
        }

        .no-strategies p {
          margin-bottom: 1rem;
        }

        .button-primary {
          background: #2196f3;
          color: white;
          border: none;
          padding: 0.5rem 1rem;
          border-radius: 4px;
          cursor: pointer;
          font-size: 0.9rem;
          font-weight: 500;
        }

        .button-primary:hover {
          background: #1976d2;
        }
      `}</style>
    </div>
  );
};

